"use client";

import { useAuth } from "@clerk/nextjs";
import { useEffect, useState } from "react";
import { AppShell } from "@/components/app-shell";
import { ScreenHeader } from "@/components/screen-header";

type ScanResult = {
  id: number;
  scan_url: string;
  tier: string;
  outputs: string;
  remediation: string;
};

function downloadFile(content: string, filename: string) {
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = filename;
  link.click();
  URL.revokeObjectURL(link.href);
}

function generateExecutiveSummary(scan: ScanResult): string {
  const lines: string[] = [];
  lines.push("BOXAI — EXECUTIVE SUMMARY");
  lines.push("=".repeat(50));
  lines.push(`Target: ${scan.scan_url}`);
  lines.push(`Scan tier: ${scan.tier}`);
  lines.push(`Scan ID: ${scan.id}`);
  lines.push("");
  lines.push("MODULE 1: PROMPT INJECTION SCAN");
  lines.push("-".repeat(40));

  const outputLines = scan.outputs.split("\n").length;
  const remediationLines = scan.remediation.split("\n").length;

  const hasVulnerabilities = /bypass|injection succeed|vulnerable|exploitable/i.test(scan.outputs);
  const hasBlocks = /blocked|filtered|rejected|refused/i.test(scan.outputs);

  if (hasVulnerabilities) {
    lines.push("RISK LEVEL: HIGH — Prompt injection bypasses detected.");
  } else if (hasBlocks) {
    lines.push("RISK LEVEL: MEDIUM — Some defenses present, partial coverage.");
  } else {
    lines.push("RISK LEVEL: LOW — No obvious injection bypass in outputs.");
  }

  lines.push("");
  lines.push(`Outputs document: ${outputLines} lines of raw scan data`);
  lines.push(`Remediation document: ${remediationLines} lines of fix recommendations`);
  lines.push("");
  lines.push("See the full outputs and remediation documents for details.");
  lines.push("=".repeat(50));

  return lines.join("\n");
}

export default function ReportsPage() {
  const { getToken } = useAuth();
  const [latestScan, setLatestScan] = useState<ScanResult | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    async function fetchLatest() {
      try {
        const token = await getToken();
        const res = await fetch("http://localhost:8000/scan/results/latest", {
          headers: { Authorization: `Bearer ${token}` },
        });
        if (res.ok) {
          setLatestScan(await res.json());
        } else if (res.status === 404) {
          setError("No scan results yet. Run a scan from the overview page first.");
        } else {
          setError("Failed to load scan results.");
        }
      } catch {
        setError("Could not reach the backend server.");
      } finally {
        setLoading(false);
      }
    }
    fetchLatest();
  }, [getToken]);

  return (
    <AppShell>
      <div className="space-y-8 pb-10">
        <ScreenHeader
          eyebrow="Reports"
          title="Scan report with downloadable documents."
          description="This screen renders the executive summary and provides direct download access to the outputs and remediation documents generated by your latest scan."
        />

        {loading && (
          <div className="rounded-[1.6rem] border border-white/10 bg-white/[0.03] p-6">
            <p className="text-sm text-slate-400 animate-pulse">Loading report…</p>
          </div>
        )}

        {error && (
          <div className="rounded-[1.6rem] border border-white/10 bg-white/[0.03] p-6">
            <p className="text-sm text-slate-400">{error}</p>
          </div>
        )}

        {latestScan && (
          <>
            <section className="grid gap-5 lg:grid-cols-3">
              <article className="rounded-[1.75rem] border border-white/10 bg-white/[0.03] p-6 shadow-[0_18px_50px_rgba(0,0,0,0.24)]">
                <p className="text-sm font-semibold uppercase tracking-[0.24em] text-slate-400">
                  Executive summary
                </p>
                <pre className="mt-4 max-h-48 overflow-y-auto rounded-xl border border-white/10 bg-black p-4 text-xs leading-5 text-slate-200 whitespace-pre-wrap">
                  {generateExecutiveSummary(latestScan)}
                </pre>
              </article>
              <article className="rounded-[1.75rem] border border-white/10 bg-white/[0.03] p-6 shadow-[0_18px_50px_rgba(0,0,0,0.24)]">
                <p className="text-sm font-semibold uppercase tracking-[0.24em] text-slate-400">
                  Evidence bundle
                </p>
                <p className="mt-4 text-sm leading-7 text-slate-300">
                  Raw payload traces, endpoint responses, and injection test results from the scan execution against <span className="font-semibold text-white break-all">{latestScan.scan_url}</span>.
                </p>
                <p className="mt-2 text-xs text-slate-400">{latestScan.outputs.split("\n").length} lines captured</p>
              </article>
              <article className="rounded-[1.75rem] border border-white/10 bg-white/[0.03] p-6 shadow-[0_18px_50px_rgba(0,0,0,0.24)]">
                <p className="text-sm font-semibold uppercase tracking-[0.24em] text-slate-400">
                  Recommended actions
                </p>
                <p className="mt-4 text-sm leading-7 text-slate-300">
                  Fix recommendations covering prompt boundary hardening, input validation improvements, and output sanitization controls.
                </p>
                <p className="mt-2 text-xs text-slate-400">{latestScan.remediation.split("\n").length} lines of guidance</p>
              </article>
            </section>

            <section className="rounded-[1.9rem] border border-white/10 bg-white/[0.03] p-6 text-slate-100 shadow-[0_20px_60px_rgba(0,0,0,0.24)]">
              <p className="text-sm font-semibold uppercase tracking-[0.24em] text-slate-300">
                Download documents
              </p>
              <h2 className="mt-2 text-3xl font-semibold tracking-tight text-white">
                Export scan artifacts.
              </h2>
              <p className="mt-4 max-w-2xl text-sm leading-7 text-slate-200">
                Download the full outputs document, remediation document, or the executive summary report.
              </p>
              <div className="mt-5 flex flex-wrap gap-3">
                <button
                  type="button"
                  onClick={() => downloadFile(latestScan.outputs, `boxai_outputs_${latestScan.id}.txt`)}
                  className="action-box action-box-cyan px-4 py-3 text-sm font-medium text-white"
                >
                  Download outputs
                </button>
                <button
                  type="button"
                  onClick={() => downloadFile(latestScan.remediation, `boxai_remediation_${latestScan.id}.txt`)}
                  className="action-box action-box-gold px-4 py-3 text-sm font-medium text-white"
                >
                  Download remediation
                </button>
                <button
                  type="button"
                  onClick={() => downloadFile(generateExecutiveSummary(latestScan), `boxai_report_${latestScan.id}.txt`)}
                  className="action-box action-box-magenta px-4 py-3 text-sm font-medium text-white"
                >
                  Download full report
                </button>
              </div>
            </section>
          </>
        )}
      </div>
    </AppShell>
  );
}