    def _calculate_cost_score(self, total_cost: float) -> float:
        """Log-normalization against MTL of $10M."""
        min_cost = 1000
        mtl = 10000000
        if total_cost <= 0:
            return 0
        score = (math.log(total_cost) - math.log(min_cost)) / (math.log(mtl) - math.log(min_cost)) * 100
        return max(0, min(100, score))

    def _calculate_hybrid_risk(self, static: float, graph: float, temporal: float, cost: float) -> int:
        """SGTC hybrid risk formula."""
        weights = {'static': 0.40, 'graph': 0.30, 'temporal': 0.20, 'cost': 0.10}
        s = static * weights['static']
        g = graph * weights['graph']
        t = temporal * weights['temporal']
        c = cost * weights['cost']
        max_floor = max(s, g, t, c) * 0.6
        euclidean = math.sqrt(s**2 + g**2 + t**2 + c**2) * 0.4
        raw = max_floor + euclidean
        max_possible = (100 * weights['static'] * 0.6) + \
            (math.sqrt((100*weights['static'])**2 + (100*weights['graph'])**2 +
                      (100*weights['temporal'])**2 + (100*weights['cost'])**2) * 0.4)
        return round((raw / max_possible) * 100)

    def get_graph_for_cytoscape(self, scan_id: str) -> dict:
        """Fetch graph from Neo4j and transform into Cytoscape.js elements format."""
        import json
        
        cyto_nodes = []
        cyto_edges = []
        stats = {}
        
        try:
            paths_res = self.supabase.table('attack_paths').select('path_nodes, hybrid_risk_score').eq('scan_id', scan_id).execute()
            paths = paths_res.data or []
            
            node_max_risk = {}
            for p in paths:
                score = p.get('hybrid_risk_score', 0)
                path_nodes_obj = p.get('path_nodes') or {}
                nodes_list = path_nodes_obj.get('nodes', []) if isinstance(path_nodes_obj, dict) else (path_nodes_obj if isinstance(path_nodes_obj, list) else [])
                for node_id in nodes_list:
                    if score > node_max_risk.get(node_id, 0):
                        node_max_risk[node_id] = score
                        
            with self.neo4j.session() as session:
                # 1. Fetch all entities (nodes) for this scan
                result = session.run("MATCH (n:Entity {scan_id: $scan_id}) RETURN n", scan_id=scan_id)
                for record in result:
                    node = record['n']
                    props_str = node.get('props', '{}')
                    try:
                        props_dict = json.loads(props_str) if isinstance(props_str, str) else props_str
                    except Exception:
                        props_dict = {}
                        
                    cyto_nodes.append({
                        "data": {
                            "id": node.get('id', ''),
                            "label": node.get('name', node.get('id', '')),
                            "type": node.get('type', 'Unknown'),
                            "provider": node.get('provider', ''),
                            "is_admin": node.get('is_admin', False),
                            "is_overprivileged": node.get('is_overprivileged', False),
                            "has_mfa": node.get('has_mfa', False),
                            "is_dormant": node.get('is_dormant', False),
                            "is_external": node.get('is_external', False),
                            "risk_score": max(
                                props_dict.get('risk_score', 0) if isinstance(props_dict, dict) else 0,
                                node_max_risk.get(node.get('id', ''), 0)
                            ),
                            "account": node.get('account', ''),
                        }
                    })
                    
                # 2. Fetch all relationships (edges) for this scan
                result = session.run(
                    "MATCH (n:Entity {scan_id: $scan_id})-[r]->(m:Entity {scan_id: $scan_id}) "
                    "RETURN n.id AS source, m.id AS target, type(r) AS rel_type, r", 
                    scan_id=scan_id
                )
                for record in result:
                    source = record['source']
                    target = record['target']
                    rel_type = record['rel_type']
                    cyto_edges.append({
                        "data": {
                            "id": f"{source}->{target}",
                            "source": source,
                            "target": target,
                            "label": rel_type,
                            "type": rel_type,
                        }
                    })
                    
        except Exception as e:
            import logging
            logging.error(f"Failed to fetch graph from Neo4j for scan {scan_id}: {e}")
            
        return {
            "elements": {
                "nodes": cyto_nodes,
                "edges": cyto_edges
            },
            "stats": stats
        }